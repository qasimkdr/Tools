#!/usr/bin/env node
// Batch research queue for hundreds of keywords (free mode). State lives in research/_queue.json; resumable.
//
//   npm run seo:batch -- init --from roadmap [--limit 400]      queue each roadmap page's primary keyword (id = page slug)
//   npm run seo:batch -- init --csv path/semrush.csv [--limit N] queue keywords from a Semrush CSV (id = keyword slug)
//   npm run seo:batch -- next --size 5                          list the next ids that need search results
//        → agent: WebSearch each keyword, then `npm run seo:record -- --slug <id> --kw "<keyword>" --results '<json>'`
//   npm run seo:batch -- run --size 5                           scrape ≥4 competitors + write report for ready ids
//   npm run seo:batch -- status                                  progress + rewrite research/INDEX.md
//
// Statuses: needs-serp → ready (serp.json exists) → done (≥4 pages + report) | partial (<4 pages; needs more URLs/hosts)
import fs from "node:fs";
import path from "node:path";
import { RESEARCH_DIR, ROOT, args, parseCSV, readJSON, slugify, writeJSON } from "./lib.mjs";
import { scrape } from "./scrape.mjs";
import { report } from "./report.mjs";

const QUEUE = path.join(RESEARCH_DIR, "_queue.json");
fs.mkdirSync(RESEARCH_DIR, { recursive: true });
const a = args();
const cmd = process.argv[2];
const q = readJSON(QUEUE, { items: [] });
const save = () => writeJSON(QUEUE, q);
const has = (id, f) => fs.existsSync(path.join(RESEARCH_DIR, id, f));
const refresh = (it) => { if (it.status === "needs-serp" && has(it.id, "serp.json")) it.status = "ready"; };

function writeIndex() {
  const c = q.items.reduce((m, it) => ((m[it.status] = (m[it.status] || 0) + 1), m), {});
  const L = ["# Research index (generated by `npm run seo:batch -- status`)", "",
    `Total ${q.items.length} · ${Object.entries(c).map(([k, v]) => `${k}: ${v}`).join(" · ")}`, "",
    "| # | Id | Keyword | Volume | KD | Status | Pages | Report |", "|---|---|---|---|---|---|---|---|"];
  q.items.forEach((it, i) => L.push(`| ${i + 1} | ${it.id} | ${it.keyword} | ${it.vol ?? "—"} | ${it.kd ?? "—"} | ${it.status} | ${it.pages ?? 0} | ${has(it.id, "report.md") ? `[report](${it.id}/report.md)` : "—"} |`));
  fs.writeFileSync(path.join(RESEARCH_DIR, "INDEX.md"), L.join("\n") + "\n");
  return c;
}

if (cmd === "init") {
  const known = new Set(q.items.map((x) => x.id));
  let add = [];
  if (a.csv) {
    add = parseCSV(fs.readFileSync(path.resolve(String(a.csv)), "utf8")).map((r) => ({ keyword: r.Keyword || r.keyword, vol: Number(r.Volume || 0) || null, kd: r["Keyword Difficulty"] ?? r.KD ?? null }))
      .filter((k) => k.keyword).map((k) => ({ ...k, id: slugify(k.keyword) }));
  } else {
    const pages = readJSON(path.join(ROOT, "data/roadmap.json"), { pages: [] }).pages.filter((p) => p.status !== "hold");
    add = pages.map((p) => ({ id: p.slug, keyword: p.primaryKw, vol: p.primaryVol, kd: p.primaryKd }));
  }
  add = add.filter((x) => !known.has(x.id)).slice(0, Number(a.limit || 100000));
  q.items.push(...add.map((x) => ({ ...x, status: "needs-serp", pages: 0 })));
  q.items.forEach(refresh); save();
  console.log(`Queued ${add.length} (total ${q.items.length}).`, writeIndex());
} else if (cmd === "next") {
  q.items.forEach(refresh); save();
  const list = q.items.filter((x) => x.status === "needs-serp").slice(0, Number(a.size || 5));
  console.log(list.length ? "Need search results (WebSearch, then seo:record):" : "Nothing needs search results.");
  for (const it of list) console.log(`  --slug ${it.id} --kw "${it.keyword}"   (vol ${it.vol ?? "—"}, KD ${it.kd ?? "—"})`);
} else if (cmd === "run") {
  q.items.forEach(refresh);
  const list = q.items.filter((x) => x.status === "ready" || (x.status === "partial" && a.retry)).slice(0, Number(a.size || 5));
  if (!list.length) console.log("No ready items. Run `next`, record search results, then `run` again.");
  for (const it of list) {
    console.log(`\n▶ ${it.id} — "${it.keyword}"`);
    try {
      const r = await scrape({ slug: it.id, count: Number(a.count || 4) });
      report({ slug: it.id });
      Object.assign(it, { pages: r.inspected, status: r.inspected >= 4 ? "done" : "partial", updatedAt: new Date().toISOString() });
      console.log(`  → ${it.status} (${r.inspected} pages) research/${it.id}/report.md`);
    } catch (e) { it.status = "partial"; it.error = e.message; console.log(`  ✗ ${e.message}`); }
    save();
  }
  console.log("\n", writeIndex());
} else if (cmd === "status") {
  q.items.forEach(refresh); save();
  console.log(writeIndex(), "→ research/INDEX.md");
} else {
  console.log("Commands: init | next | run | status  (see header of scripts/seo/batch.mjs)");
}
