#!/usr/bin/env node
// Pre-build step (runs automatically before `npm run build` and `npm run lint`).
// Scheduled tools have `publishAt: "<ISO time with offset>"` in meta.ts and keep their route module in
// src/tools/<slug>/page.tsx (NOT in src/app). Only tools whose publishAt has passed get a route here, so an
// unpublished tool has no page, no sitemap entry and no links anywhere until its time.
//   SHOW_SCHEDULED=1  → include every scheduled tool (CI tests the whole queue with this).
// Writes: src/app/(scheduled)/<slug>/page.tsx (generated, git-ignored) and src/tools/scheduled-live.json.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const toolsDir = path.join(root, "src/tools");
const outDir = path.join(root, "src/app/(scheduled)");
const show = process.env.SHOW_SCHEDULED === "1";
const now = Date.now();

const scheduled = [];
for (const slug of fs.readdirSync(toolsDir)) {
  const metaFile = path.join(toolsDir, slug, "meta.ts");
  if (!fs.existsSync(metaFile)) continue;
  const at = fs.readFileSync(metaFile, "utf8").match(/publishAt:\s*"([^"]+)"/)?.[1];
  if (!at) continue;
  const t = Date.parse(at);
  if (Number.isNaN(t)) throw new Error(`${slug}: invalid publishAt "${at}"`);
  if (!fs.existsSync(path.join(toolsDir, slug, "page.tsx"))) throw new Error(`${slug}: scheduled tools need src/tools/${slug}/page.tsx`);
  if (fs.existsSync(path.join(root, "src/app", slug))) throw new Error(`${slug}: scheduled tools must not have src/app/${slug}/ (it would publish immediately)`);
  scheduled.push({ slug, at, t });
}

fs.rmSync(outDir, { recursive: true, force: true });
const live = scheduled.filter((s) => show || s.t <= now).sort((a, b) => a.t - b.t);
for (const s of live) {
  fs.mkdirSync(path.join(outDir, s.slug), { recursive: true });
  fs.writeFileSync(path.join(outDir, s.slug, "page.tsx"),
    `// Generated by scripts/publish-scheduled.mjs: do not edit.\nexport { default, metadata } from "@/tools/${s.slug}/page";\n`);
}
fs.writeFileSync(path.join(toolsDir, "scheduled-live.json"), JSON.stringify({ published: live.map((s) => s.slug) }, null, 1) + "\n");
const waiting = scheduled.filter((s) => !live.includes(s)).sort((a, b) => a.t - b.t);
console.log(`Scheduled tools: ${live.length} published${show ? " (SHOW_SCHEDULED=1)" : ""}, ${waiting.length} waiting` +
  (waiting.length ? ` (next: ${waiting[0].slug} at ${waiting[0].at})` : ""));
